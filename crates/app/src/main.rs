//! 404-snf CA35 application.
//!
//! Orchestrates the full upper layer:
//!
//! 1. sends the IWR6843 its configuration profile over the sensor's 115 200-baud
//!    CLI tty ([`snf_radar::RadarCli`]) — the sensor boots idle and its data
//!    port stays silent until that profile's `sensorStart` runs — then reads
//!    frames via [`snf_radar`] from the 921 600-baud data tty, both over the
//!    sensor's USB virtual COM port and so both a plain `tokio-serial` read,
//! 2. extracts indicators, windows them into model features via
//!    [`snf_bridge::features`], and classifies fatigue via [`snf_fatigue`]
//!    (ONNX) — then decides through [`snf_bridge::confidence`] how much of that
//!    verdict the actuators are allowed to see,
//! 3. turns that fatigue level into a deformation through
//!    [`snf_bridge::inflation`] and drives the pneumatics directly — two
//!    symmetric sections on `TIM4_CH2` and `TIM5_CH1`, both through FR120N
//!    MOSFET modules (see [`pneumatics`] / [`fr120n`] / [`sysfs_pwm`]), and
//! 4. publishes vitals, fatigue and status over BLE via [`snf_ble`] (BlueZ).
//!
//! So the whole data path is on this core. TIM4/TIM5 are reachable only from the
//! AP, which is why the pneumatics are here; the CM33 holds no actuator line,
//! which means there is no independent interlock — see [`pneumatics`] for how
//! shutdown is made fail-safe instead.
//!
//! The CM33 still owns USART6 and still offers parsed frames over the `radar`
//! IPC channel (see `crates/mcu`), but that is **not** the default source: with
//! the sensor on virtual COM there is nothing on USART6 to read. All this binary
//! ever does with the channel is ping it once — and only when `[mcu] link_check`
//! asks, since a silent CM33 costs this build nothing.
//!
//! Reading runs in its own task so a `tokio::select!` branch firing never cancels
//! a partial UART read.
//!
//! The UIO bring-up, IPC transceivers, and defmt console live in
//! `consortium.gen.rs`, generated by `csti build` from `../../Consortium.toml`
//! and `include!`d below. `#[consortium_runtime_app::main]` calls the generated
//! `init()` and hands the body a `Context` whose `ipc_shm.radar` field is a
//! ready `Transceiver<RadarControl, RadarReport>`.

#![cfg(target_os = "linux")]

use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

use snf_ble::{
    BleTransport, Telemetry,
    protocol::{ControlOp, Fatigue, ProtocolInfo, Vitals, capabilities, header_flags, streams},
};
use snf_bridge::{
    Accounting, FeatureExtractor, StreamState, Trust, confidence,
    inflation::{Actuation, InflationController, InflationMode},
    map,
};
use snf_fatigue::FatigueModel;
use snf_radar::{IndicatorEngine, RadarCli, RadarCliConfig, RadarConfig, RadarFrame, RadarStream};
use snf_shared::{RadarControl, RadarReport};

mod config;
mod fr120n;
mod pneumatics;
mod sysfs_pwm;

use pneumatics::{PneumaticState, Pneumatics};

/// Firmware build id for Protocol Info; `0` until wired to the build system.
const BUILD_ID: u32 = 0;
/// Device Status notify period (`PROTOCOL.md` §13 default: 1 Hz).
const STATUS_PERIOD: Duration = Duration::from_secs(1);
/// How often the pneumatic state is re-evaluated. Independent of the radar so
/// the inflation budgets and ceilings in
/// [`InflationController`](snf_bridge::inflation::InflationController) still
/// advance if frames stop mid-inflation.
const ACTUATOR_PERIOD: Duration = Duration::from_millis(100);
/// Streams this build can serve: no pose model yet, so `POSE_3D` stays clear.
const DEVICE_CAPABILITIES: u32 = capabilities::VITALS | capabilities::FATIGUE;
/// Upper bound on point-cloud points advertised in Protocol Info.
const MAX_POINTS: u8 = 96;

/// A best-effort boot identifier that changes across restarts, so clients can
/// detect a reboot and flush per-sequence state (`PROTOCOL.md` §14).
fn boot_id() -> u32 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.subsec_nanos() ^ (d.as_secs() as u32))
        .unwrap_or(0)
}

/// Minimum spacing between Vitals notifications for a requested rate.
fn vitals_period(hz: u8) -> Duration {
    Duration::from_millis(1000 / hz.max(1) as u64)
}

/// A radar frame or a gap, forwarded from the reader task. Reading runs in its
/// own task so a `tokio::select!` branch firing never cancels a partial UART
/// read.
enum RadarEvent {
    Frame(RadarFrame),
    Gap,
}

/// Translate the control model's decision into the actuator pair's state.
///
/// The two enums are deliberately separate: `snf-bridge` decides *what should
/// happen* without knowing there is a MOSFET on the other end, and this crate
/// owns everything about how the two sections are driven.
fn pneumatic_state(actuation: Actuation) -> PneumaticState {
    match actuation {
        Actuation::Vent => PneumaticState::Vent,
        Actuation::Cycle(duty) => PneumaticState::Cycle(duty),
    }
}

// Generated by `csti build`; absent until the pipeline runs (see this crate's
// README). Not compiled by the workspace `cargo check`.
include!("consortium.gen.rs");

/// Reports a bring-up failure and exits. Hit when `init()` cannot open the UIO
/// devices or the descriptor handshake fails — most often a plain dev host with
/// no `/dev/uioN`.
#[consortium_runtime_app::fail]
fn on_init_failure(err: ConsortiumInitError) {
    init_logging();
    tracing::error!("snf-app: IPC bring-up failed: {err:?}");
}

/// Install the subscriber. The filter comes from `RUST_LOG`, or failing that the
/// `log` key in `Repose.toml` — see [`config::log_filter`] for why the file is
/// consulted here rather than after it has been properly loaded.
fn init_logging() {
    tracing_subscriber::fmt()
        .with_env_filter(config::log_filter())
        .init();
}

#[consortium_runtime_app::main]
async fn main(mut context: Context) {
    init_logging();
    tracing::info!("snf-app: CA35 application started; IPC bring-up complete");

    // ── Where the hardware is ────────────────────────────────────────────────
    // `Repose.toml` beside the binary, or the compiled-in defaults if there is
    // none. A file that exists but cannot be honoured stops here rather than
    // being partly applied — see `config` for why the two cases differ.
    let config = match config::load() {
        Ok(config) => config,
        Err(e) => {
            tracing::error!("snf-app: configuration error: {e}");
            return;
        }
    };
    config.log_summary();

    // ── BLE peripheral: advertise and serve the SNF telemetry service ────────
    let info = ProtocolInfo {
        capabilities: DEVICE_CAPABILITIES,
        max_point_count: MAX_POINTS as u16,
        max_pose_joints: 0,
        max_subjects: 1,
        boot_id: boot_id(),
        build_id: BUILD_ID,
    };
    let mut ble = snf_ble::BluezPeripheral::new(config.ble.adapter.clone(), info);
    if let Err(e) = ble.start().await {
        tracing::error!("snf-app: BLE start failed: {e}");
        return;
    }
    let mut control = ble
        .control_requests()
        .expect("control receiver is taken exactly once");
    let mut stream_state = StreamState::default();
    let mut accounting = Accounting::new(stream_state.stream_mask);

    // ── Pneumatics: symmetric sections on TIM4_CH2 and TIM5_CH1 ──────────────
    // Optional: without the PWM chips (wrong device tree, wrong chip index) the
    // sensing half is still worth running, so this degrades to telemetry-only
    // rather than refusing to start.
    let mut pneumatics = match Pneumatics::open(config.pneumatics.into()) {
        Ok(pneumatics) => Some(pneumatics),
        Err(e) => {
            tracing::warn!("snf-app: pneumatics unavailable ({e}); running without actuation");
            None
        }
    };

    // ── Radar configuration: the sensor's other UART ─────────────────────────
    // The IWR6843 boots idle. Its 115 200-baud CLI port takes the profile, whose
    // last line is `sensorStart`, and only then does the 921 600-baud data port
    // produce a single byte — so this has to happen before the data port is
    // opened, and a failure here is fatal rather than degraded: there is no
    // partial sensing to fall back to, and the next thing to go wrong would be a
    // silent UART that looks like a wiring fault.
    if config.radar.configure_on_connect {
        let cli_config: RadarCliConfig = config.radar.clone().into();
        match RadarCli::configure(&cli_config).await {
            Ok(report) => {
                tracing::info!(
                    "snf-app: radar configured over {} ({} commands)",
                    cli_config.cli_port,
                    report.commands
                );
                // `Debug: Init Calibration Status = …` from `sensorStart` lands
                // here, which is the line worth having in the journal.
                for note in report.notes {
                    tracing::info!("snf-app: radar {note}");
                }
            }
            Err(e) => {
                tracing::error!(
                    "snf-app: radar configuration on {} failed: {e}",
                    cli_config.cli_port
                );
                return;
            }
        }
    } else {
        tracing::info!(
            "snf-app: radar.configure_on_connect = false; expecting the sensor to have been \
             started elsewhere"
        );
    }

    // ── Radar pipeline: read frames in a task, extract indicators here ───────
    let radar_config: RadarConfig = config.radar.clone().into();
    let data_port = radar_config.data_port.clone();
    let radar = match RadarStream::open(radar_config) {
        Ok(radar) => radar,
        Err(e) => {
            tracing::error!("snf-app: radar open on {data_port} failed: {e}");
            return;
        }
    };
    let (frame_tx, mut frame_rx) = tokio::sync::mpsc::channel::<RadarEvent>(4);
    tokio::spawn(read_radar(radar, frame_tx));
    let mut indicators = IndicatorEngine::default();

    // The rolling window and personal baselines the model reads. Fed at the
    // vitals rate, matching the feature contract documented in `ml/`.
    let mut features = FeatureExtractor::new();

    // Fatigue is optional: without a model we still publish vitals and status.
    let mut fatigue_model = match FatigueModel::load(&config.fatigue.model_path) {
        Ok(model) => Some(model),
        Err(e) => {
            tracing::warn!(
                "snf-app: fatigue model unavailable at {} ({e}); running without fatigue",
                config.fatigue.model_path
            );
            None
        }
    };

    // ── CM33 link check: opt-in, advisory, and last ──────────────────────────
    // The IPC descriptor handshake already happened in `init()`; this is the
    // separate question of whether anything is *answering* on the other side.
    // The CM33 owns USART6, which carries nothing in the virtual-COM
    // configuration, so its front-end is not on the path to a single reading —
    // which is why this runs after the sensing pipeline is up, is off unless a
    // board asks for it, and treats silence as a warning. A CM33 that is
    // unflashed, held in reset, or simply slow must not cost the sensing half
    // anything, and before the timeout it could stall start-up indefinitely.
    if config.mcu.link_check {
        check_cm33_link(
            &mut context,
            Duration::from_millis(config.mcu.link_check_timeout_ms),
        )
        .await;
    }

    let mut status_tick = tokio::time::interval(STATUS_PERIOD);
    let mut actuator_tick = tokio::time::interval(ACTUATOR_PERIOD);
    let mut last_vitals_at: Option<Instant> = None;

    // The latest record of each on-demand stream, replayed with the `SNAPSHOT`
    // flag when a client asks for one (`PROTOCOL.md` §12). They start at the
    // warming-up defaults because a snapshot taken before the first reading
    // still has to answer with a decodable message rather than nothing — the
    // ESP32-C5 synthesises one from its (initially warming-up) sample the same
    // way.
    let mut last_vitals = (Vitals::warming_up(), 0u8);
    let mut last_fatigue = Fatigue::warming_up(config.fatigue.revision);

    // The fatigue → inflation-speed model: which deformation mode the current
    // fatigue level calls for, how fast to approach it, and the hysteresis and
    // charge ceilings that bound it. Canopy stays disarmed: it is the one mode
    // that must not follow from fatigue alone, and Stream Control (`PROTOCOL.md`
    // §12) has no opcode for the explicit user trigger yet.
    let mut inflation = InflationController::default();
    let mut last_mode = InflationMode::default();
    // Whether verdicts are currently being withheld for low confidence. Tracked
    // only so the transition is logged once instead of at the vitals rate.
    let mut withholding = false;

    loop {
        tokio::select! {
            // Radar frame → indicators → Vitals (rate-limited) + Fatigue.
            Some(event) = frame_rx.recv() => {
                let RadarEvent::Frame(frame) = event else {
                    accounting.note_radar_gap();
                    continue;
                };
                if let Some(temperature_c) = frame
                    .temperature_stats
                    .as_ref()
                    .and_then(|stats| stats.processor_temperature_c())
                {
                    accounting.set_processor_temp_c(f32::from(temperature_c));
                }
                let now = Instant::now();
                let snapshot = indicators.update(now, &frame);

                let vitals_due = last_vitals_at
                    .is_none_or(|last| now.duration_since(last) >= vitals_period(stream_state.vitals_hz));
                if !vitals_due {
                    continue;
                }
                last_vitals_at = Some(now);

                // Mapped unconditionally so a snapshot request answers with the
                // current reading even while the stream is switched off.
                let mapped = map::vitals(&snapshot);
                last_vitals = (mapped.payload, mapped.header_flags);
                if stream_state.stream_mask & streams::VITALS != 0 {
                    if let Err(e) = ble.publish(Telemetry::Vitals(mapped.payload), mapped.header_flags).await {
                        tracing::warn!("snf-app: vitals publish failed: {e}");
                    }
                }

                // Fatigue drives both the BLE record and the pneumatics, so it
                // runs whether or not anyone is subscribed to that stream.
                if let Some(model) = fatigue_model.as_mut() {
                    match model.infer(&features.update(now, &snapshot)) {
                        Ok(verdict) => {
                            // How sure the model is decides how much of the
                            // verdict reaches the actuators. Below the floor the
                            // controller is told nothing at all, so its own
                            // `verdict_timeout` pins the sections to neutral —
                            // an uncertain model makes the mat quieter, never
                            // busier. See `snf_bridge::confidence`.
                            match confidence::gate(verdict) {
                                Trust::Applied { level, weight } => {
                                    if withholding {
                                        tracing::info!(
                                            "snf-app: verdicts trusted again (confidence {:.2})",
                                            verdict.confidence,
                                        );
                                        withholding = false;
                                    }
                                    tracing::trace!(
                                        "snf-app: fatigue {} x {weight:.2} -> {level}",
                                        verdict.level,
                                    );
                                    inflation.observe(now, level);
                                }
                                Trust::Withheld { reported_level } => {
                                    // Logged on the transition only: at the
                                    // vitals rate this would otherwise be two
                                    // lines a second for as long as the radar
                                    // cannot see well enough to be sure.
                                    if !withholding {
                                        tracing::info!(
                                            "snf-app: withholding verdicts \
                                             (level {reported_level}, confidence {:.2} < {:.2}); \
                                             not actuating",
                                            verdict.confidence,
                                            confidence::ACTION_FLOOR,
                                        );
                                        withholding = true;
                                    }
                                }
                            }

                            // Published either way, with `LOW_CONFIDENCE` set
                            // when it was withheld — a client should see what
                            // the model thought *and* that the device did not
                            // act on it.
                            let payload =
                                map::fatigue_telemetry(verdict, config.fatigue.revision);
                            last_fatigue = payload;
                            if stream_state.stream_mask & streams::FATIGUE != 0 {
                                if let Err(e) = ble.publish(Telemetry::Fatigue(payload), 0).await {
                                    tracing::warn!("snf-app: fatigue publish failed: {e}");
                                }
                            }
                        }
                        Err(e) => tracing::warn!("snf-app: inference failed: {e}"),
                    }
                }
            }

            // Stream Control request from a BLE client.
            Some(request) = control.recv() => {
                let response = stream_state.apply(&request, DEVICE_CAPABILITIES, MAX_POINTS);
                accounting.active_streams = stream_state.stream_mask;

                // `REQUEST_SNAPSHOT` has to actually deliver the frames — the
                // response only reports which streams were servable. Gated on
                // the active mask, so a snapshot never revives a stream the
                // client turned off (`PROTOCOL.md` §12).
                if let ControlOp::RequestSnapshot(mask) = request.op {
                    let due = mask & stream_state.stream_mask;
                    if due & streams::STATUS != 0 {
                        let payload = accounting.snapshot();
                        if let Err(e) = ble
                            .publish(Telemetry::Status(payload), header_flags::SNAPSHOT)
                            .await
                        {
                            tracing::warn!("snf-app: status snapshot failed: {e}");
                        }
                    }
                    if due & streams::VITALS != 0 {
                        let (payload, flags) = last_vitals;
                        if let Err(e) = ble
                            .publish(Telemetry::Vitals(payload), flags | header_flags::SNAPSHOT)
                            .await
                        {
                            tracing::warn!("snf-app: vitals snapshot failed: {e}");
                        }
                    }
                    if due & streams::FATIGUE != 0 {
                        if let Err(e) = ble
                            .publish(Telemetry::Fatigue(last_fatigue), header_flags::SNAPSHOT)
                            .await
                        {
                            tracing::warn!("snf-app: fatigue snapshot failed: {e}");
                        }
                    }
                }

                if let Err(e) = ble.respond(response).await {
                    tracing::warn!("snf-app: control response failed: {e}");
                }
            }

            // Device Status notify (1 Hz).
            _ = status_tick.tick() => {
                if stream_state.stream_mask & streams::STATUS != 0 {
                    if let Err(e) = ble.publish(Telemetry::Status(accounting.snapshot()), 0).await {
                        tracing::warn!("snf-app: status publish failed: {e}");
                    }
                }
            }

            // Apply the actuator state. On its own tick rather than inline with
            // the fatigue verdict, so the budgets, the charge ceiling and the
            // release dwell all keep running — and a stale verdict still pins
            // the sections to neutral — when the radar goes quiet mid-inflation.
            _ = actuator_tick.tick() => {
                let command = inflation.command(Instant::now());
                if command.mode != last_mode {
                    tracing::info!(
                        "snf-app: inflation mode {last_mode:?} -> {:?} (speed {:.2})",
                        command.mode,
                        command.speed,
                    );
                    last_mode = command.mode;
                }

                let mut failed = false;
                if let Some(actuators) = pneumatics.as_mut() {
                    let desired = pneumatic_state(command.actuation);
                    if desired != actuators.state() {
                        match actuators.set_state(desired) {
                            Ok(()) => tracing::debug!("snf-app: pneumatics -> {desired:?}"),
                            Err(e) => {
                                tracing::error!("snf-app: pneumatics write failed: {e}; venting");
                                // `set_state` has already rolled both sections
                                // back to vent — a half-applied write would
                                // leave the mat lopsided. Confirm it, then give
                                // up actuating rather than keep poking a broken
                                // PWM chip.
                                let _ = actuators.set_state(PneumaticState::Vent);
                                failed = true;
                            }
                        }
                    }
                }
                if failed {
                    // Dropping vents again and unexports both channels, leaving
                    // the pins low; telemetry keeps running.
                    pneumatics = None;
                }
            }
        }
    }
}

/// Ping the CM33 once and log its reply, so a shared-memory link with nothing
/// behind it shows up at start-up rather than the first time something needs it.
///
/// Every outcome is advisory. The CM33's front-end serves a wiring this build
/// does not use, so no answer is a warning and never a reason to stop: a board
/// whose CM33 is unflashed or held in reset still senses, classifies, actuates
/// and publishes exactly as before.
///
/// `streaming: false` parks that front-end: nothing is wired to USART6 in the
/// virtual-COM configuration, so there is no reason for it to spin. The transfer
/// is a strict pull (see `crates/mcu`), so a CM33 that never hears this simply
/// stays idle in `recv` — skipping the check leaves nothing running.
async fn check_cm33_link(context: &mut Context, timeout: Duration) {
    let request = RadarControl {
        seq: 0,
        streaming: false,
    };
    if let Err(e) = context.ipc_shm.radar.send(&request).await {
        tracing::warn!("snf-app: CM33 link check send failed: {e}");
        return;
    }
    // Abandoning `recv` mid-flight is safe only because this is the sole reader
    // of the channel and it runs exactly once: nothing later depends on where a
    // cancelled receive left off.
    match tokio::time::timeout(timeout, context.ipc_shm.radar.recv()).await {
        Ok(Ok(message)) => {
            let report: RadarReport = message.into_inner();
            tracing::info!("snf-app: CM33 link up (report seq={})", report.seq);
        }
        Ok(Err(e)) => tracing::warn!("snf-app: CM33 link check recv failed: {e}"),
        Err(_) => tracing::warn!(
            "snf-app: no CM33 reply within {} ms; continuing without the USART6 front-end",
            timeout.as_millis()
        ),
    }
}

/// Read radar frames until the stream ends, forwarding each as a [`RadarEvent`].
/// Runs in its own task so `next_frame`'s UART read is never cancelled by the
/// main loop's `select!`.
async fn read_radar(mut radar: RadarStream, tx: tokio::sync::mpsc::Sender<RadarEvent>) {
    loop {
        match radar.next_frame().await {
            Ok(Some(frame)) => {
                if tx.send(RadarEvent::Frame(frame)).await.is_err() {
                    break; // main loop dropped the receiver
                }
            }
            Ok(None) => {
                tracing::warn!("snf-app: radar stream ended");
                break;
            }
            Err(e) => {
                tracing::warn!("snf-app: radar frame error: {e}");
                if tx.send(RadarEvent::Gap).await.is_err() {
                    break;
                }
            }
        }
    }
}
